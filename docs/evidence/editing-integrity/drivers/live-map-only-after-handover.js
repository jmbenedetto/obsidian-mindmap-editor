const check=(ok,message)=>{if(!ok)throw Error(message);};
const file=app.vault.getAbstractFileByPath('MapOnly-Verified.md');
check(await app.vault.adapter.read(file.path)==='# Initial\n','Earlier refusal changed the fixture');
const mapLeaf=app.workspace.getLeavesOfType('mindmap-editor').find(leaf=>leaf.view.currentFile===file);
const map=mapLeaf.view;
const leaf=app.workspace.getLeaf('split','vertical');
await leaf.openFile(file,{active:true});
await leaf.setViewState({type:'markdown',state:{file:file.path,mode:'source',source:true}});
const old=leaf.view;
map.containerEl.querySelector('[aria-label="Acquire exclusive map editing"]').click();
await map.acquiring;
check(map.authority&&!map.authority.retired&&old.file===null,'Handover did not revoke the source');
leaf.detach();
app.workspace.setActiveLeaf(mapLeaf,{focus:true});
await new Promise(resolve=>requestAnimationFrame(resolve));
await map.render();
check(map.scrollerEl.clientWidth>100&&getComputedStyle(map.canvasEl).visibility==='visible','Map-only view is not visibly laid out');
const node=map.root.children[0];
map.startInlineEdit(node,map.laidByLine.get(node.line).el);
const input=map.canvasEl.querySelector('.mindmap-edit-input');
check(input?.isConnected,'Map-only editor did not open');
input.innerText='Map-only 👩🏽‍💻';
input.dispatchEvent(new InputEvent('input',{bubbles:true,inputType:'insertText',data:input.innerText}));
await map.closeEdit();
await map.sourceQueue;
await map.render();
const after=await app.vault.adapter.read(file.path);
check(after==='# Map-only 👩🏽‍💻\n','Map-only final label mismatch');
check(!app.workspace.getLeavesOfType('markdown').length&&!app.workspace.getLeavesOfType('mindmap-editor-inert-source').length,'A source pane remained');
return {kind:'actual host APIs and synthetic DOM input, not physical input',mode:'map only after acknowledged handover, then inert-preview closure',fixture:file.path,markdownPanes:0,inertPanes:0,oldSourceRevoked:old.file===null,after,pass:true};
