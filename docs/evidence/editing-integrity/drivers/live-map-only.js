const check=(ok,message)=>{if(!ok)throw Error(message);};
for(const leaf of app.workspace.getLeavesOfType('mindmap-editor'))await leaf.setViewState({type:'empty'});
const name='MapOnly-Verified.md';
check(!app.vault.getAbstractFileByPath(name),'Do not replay '+name);
const file=await app.vault.create(name,'# Initial\n');
const plugin=app.plugins.plugins['mindmap-editor'];
await plugin.openMindmap(file,false);
const mapLeaf=app.workspace.getLeavesOfType('mindmap-editor')[0];
const map=mapLeaf.view;
check(!app.workspace.getLeavesOfType('markdown').some(leaf=>leaf.view.file===file),'Fixture acquired a Markdown pane');
const leaves=[];app.workspace.iterateAllLeaves(leaf=>{leaves.push(leaf);});
for(const leaf of leaves)if(leaf!==mapLeaf)leaf.detach();
app.workspace.setActiveLeaf(mapLeaf,{focus:true});
await map.setFile(file);
await map.render();
map.containerEl.querySelector('[aria-label="Acquire exclusive map editing"]').click();
await map.acquiring;
await map.render();
check(map.authority&&!map.authority.retired&&map.currentFile===file,'Map-only authority failed');
for(let n=0;n<30&&(map.renderSnapshot||map.layoutBuildSeq!==null);n++)await new Promise(resolve=>requestAnimationFrame(resolve));
check(map.scrollerEl.clientWidth>100&&getComputedStyle(map.canvasEl).visibility==='visible','Map-only view is not visibly laid out');
const node=map.root.children[0];
map.startInlineEdit(node,map.laidByLine.get(node.line).el);
const input=map.canvasEl.querySelector('.mindmap-edit-input');
check(input?.isConnected,'Map-only editor did not open');
input.innerText='Map-only 👩🏽‍💻';
input.dispatchEvent(new InputEvent('input',{bubbles:true,inputType:'insertText',data:input.innerText}));
await map.closeEdit();
await map.sourceQueue;
await map.render();
const after=await app.vault.adapter.read(name);
check(after==='# Map-only 👩🏽‍💻\n','Map-only final label mismatch');
return {kind:'actual host APIs and synthetic DOM input, not physical input',mode:'map only',fixture:name,markdownPanes:app.workspace.getLeavesOfType('markdown').length,after,pass:true};
