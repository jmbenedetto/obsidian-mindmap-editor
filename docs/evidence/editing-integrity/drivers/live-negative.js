const f=window.integrityFlow;
if(!f)throw Error('Positive flow did not finish');
const {map,file,leaf,mapLeaf,baseline}=f;
const check=(ok,message)=>{if(!ok)throw Error(message);};
const marker=baseline+'<!-- EXTERNAL marker — preserve me -->\n';
const kept=map.undoable;
check(Object.isFrozen(kept),'Undo record is not frozen');
await app.vault.modify(file,marker);
const prior=map.sourceQueue;
check(map.undoLastWrite(),'Undo was not handled');
for(let n=0;n<30&&map.sourceQueue===prior;n++)await Promise.resolve();
check(map.sourceQueue!==prior,'Undo did not enqueue');
await map.sourceQueue;
await map.render();
check(await app.vault.adapter.read(file.path)===marker&&map.undoable===kept,'Conflicting Undo changed the marker or consumed its record');
await map.releaseAuthority();
await leaf.openFile(file,{active:true});
await leaf.setViewState({type:'markdown',state:{file:file.path,mode:'source',source:true}});
check(leaf.view.getViewData()===marker,'First release did not load the actual disk buffer');
const revokedSource=leaf.view;
map.containerEl.querySelector('[aria-label="Acquire exclusive map editing"]').click();
await map.acquiring;
await map.render();
app.workspace.setActiveLeaf(mapLeaf,{focus:true});
await new Promise(resolve=>requestAnimationFrame(resolve));
check(map.authority&&!map.authority.retired,'Could not reacquire for the separate draft-conflict case');
const draftMarker=marker+'<!-- DRAFT external marker -->\n';
const visit=n=>n.text==='Alpha'?n:n.children.map(visit).find(Boolean);
const node=visit(map.root);
map.startInlineEdit(node,map.laidByLine.get(node.line).el);
const input=map.canvasEl.querySelector('.mindmap-edit-input');
check(input?.isConnected,'Could not open conflict draft');
const raw='unacknowledged 👩🏽‍💻 é\nraw extra';
input.innerText=raw;
input.dispatchEvent(new InputEvent('input',{bubbles:true,inputType:'insertText',data:raw}));
await app.vault.modify(file,draftMarker);
await map.closeEdit();
const record=app.mindmapEditorRecovery.find(d=>d.text===raw&&d.error);
check(record&&await app.vault.adapter.read(file.path)===draftMarker,'Conflict discarded raw input or changed original bytes');
await map.releaseAuthority();
await leaf.openFile(file,{active:true});
await leaf.setViewState({type:'markdown',state:{file:file.path,mode:'source',source:true}});
check(leaf.view!==revokedSource&&leaf.view.getViewData()===draftMarker&&leaf.view.containerEl.inert===false,'Release did not permit a fresh writable Source pane');
const recovery=app.mindmapEditorRecovery;
await mapLeaf.setViewState({type:'empty'});
await app.plugins.unloadPlugin('mindmap-editor');
await app.plugins.loadPlugin('mindmap-editor');
check(app.mindmapEditorRecovery===recovery&&recovery.includes(record),'View/plugin disposal lost recovery memory');
app.commands.executeCommandById('mindmap-editor:recover-map-drafts');
const area=[...document.querySelectorAll('textarea.mindmap-recovery-draft')].find(el=>el.value===raw);
check(area?.readOnly,'Actual recovery modal did not expose exact raw text');
area.scrollIntoView({block:'center'});
return {kind:'actual host APIs, actual disk and synthetic DOM events; no physical input',undo:{status:'SAFE REFUSAL',recordRetained:true,markerPreserved:true},draft:{status:'SAFE REFUSAL',raw,revision:record.revision,applied:record.applied,error:record.error,modalExact:true},releaseToSource:true,viewAndPluginReloadRecovery:true,after:await app.vault.adapter.read(file.path)};
